    "    }\n"
    "    joblib.dump(obj, path)\n"
    "    print(f\"[CHECKPOINT] Saved: {path}\")\n"
    "\n"
    "def load_checkpoint(name: str) -> dict | None:\n"
    "    \"\"\"Load checkpoint if exists.\"\"\"\n"
    "    path = os.path.join(CHECKPOINT_DIR, f'{name}.pkl')\n"
    "    if os.path.exists(path):\n"
    "        obj = joblib.load(path)\n"
    "        meta = obj.get('_checkpoint_meta', {})\n"
    "        print(f\"[CHECKPOINT] Loaded: {path} (saved {meta.get('timestamp', 'unknown')})\")\n"
    "        return obj\n"
    "    return None\n"
    "\n"
    "def checkpoint_exists(name: str) -> bool:\n"
    "    return os.path.exists(os.path.join(CHECKPOINT_DIR, f'{name}.pkl'))\n"
