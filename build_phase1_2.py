# CELL 6: Preprocessing
# ============================================================
cells.append(nbf.v4.new_markdown_cell("## 6. Preprocessing Pipeline (Checkpointed)"))
cells.append(nbf.v4.new_code_cell(
    "# Build preprocessing with checkpoint\n"
    "CHECKPOINT_NAME = 'phase2_preprocess'\n"
    "\n"
    "ckpt = load_checkpoint(CHECKPOINT_NAME)\n"
    "if ckpt:\n"
    "    preprocess_linear = ckpt['preprocess_linear']\n"
    "    preprocess_tree = ckpt['preprocess_tree']\n"
    "    preprocess_nn = ckpt['preprocess_nn']\n"
    "    le = ckpt['le']\n"
    "    X_train_linear = ckpt['X_train_linear']\n"
    "    X_test_linear = ckpt['X_test_linear']\n"
    "    X_train_tree = ckpt['X_train_tree']\n"
    "    X_test_tree = ckpt['X_test_tree']\n"
    "    X_train_nn = ckpt['X_train_nn']\n"
    "    X_test_nn = ckpt['X_test_nn']\n"
    "    y_train = ckpt['y_train']\n"
    "    y_test = ckpt['y_test']\n"
    "    class_weight_dict = ckpt['class_weight_dict']\n"
    "    print(\"Loaded cached preprocessing\")\n"
    "else:\n"
    "    print(\"Building preprocessing pipeline...\")\n"
    "    \n"
    "    # Feature engineering\n"
    "    def add_features(frame):\n"
    "        out = frame.copy()\n"
    "        out['med_change'] = (out['change'] == 'Ch').astype(int)\n"
    "        out['diabetes_med_flag'] = (out['diabetesMed'] == 'Yes').astype(int)\n"
    "        out['insulin_used'] = out['insulin'].isin(['Up', 'Down', 'Steady']).astype(int)\n"
    "        def age_to_mid(bracket):\n"
    "            if isinstance(bracket, str) and bracket.startswith('['):\n"
    "                parts = bracket.strip('[]()').split('-')\n"
    "                try:\n"
    "                    return (int(parts[0]) + int(parts[1])) / 2\n"
    "                except:\n"
    "                    return np.nan\n"
    "            return np.nan\n"
    "        out['age_mid'] = out['age'].apply(age_to_mid)\n"
    "        return out\n"
    "    \n"
    "    df_feat = add_features(df)\n"
    "    new_cols = [c for c in df_feat.columns if c not in df.columns]\n"
    "    print(f\"New features: {new_cols}\")\n"
    "    \n"
    "    # Patient-level split\n"
    "    patients = df_feat['patient_nbr'].unique()\n"
    "    train_patients, test_patients = train_test_split(\n"
    "        patients, test_size=0.2, random_state=SEED, shuffle=True\n"
    "    )\n"
    "    train_mask = df_feat['patient_nbr'].isin(train_patients)\n"
    "    test_mask = df_feat['patient_nbr'].isin(test_patients)\n"
    "    train_df = df_feat[train_mask].copy()\n"
    "    test_df = df_feat[test_mask].copy()\n"
    "    print(f\"Train: {len(train_df)} rows, {len(train_patients)} patients\")\n"
    "    print(f\"Test:  {len(test_df)} rows, {len(test_patients)} patients\")\n"
    "    \n"
    "    # Drop columns\n"
    "    drop_cols = ['encounter_id', 'patient_nbr', 'weight', 'age']\n"
    "    train_X = train_df.drop(columns=drop_cols + ['readmitted'])\n"
    "    train_y = train_df['readmitted'].copy()\n"
    "    test_X = test_df.drop(columns=drop_cols + ['readmitted'])\n"
    "    test_y = test_df['readmitted'].copy()\n"
    "    \n"
    "    # Column types\n"
    "    numeric_cols = train_X.select_dtypes(include=['int64', 'float64']).columns.tolist()\n"
    "    cat_cols = train_X.select_dtypes(include=['object']).columns.tolist()\n"
    "    code_cols = ['admission_type_id', 'discharge_disposition_id', 'admission_source_id']\n"
    "    for c in code_cols:\n"
    "        if c in numeric_cols:\n"
    "            numeric_cols.remove(c)\n"
    "            cat_cols.append(c)\n"
    "    \n"
    "    # Pipelines\n"
    "    numeric_pipe = Pipeline([\n"
    "        ('imputer', SimpleImputer(strategy='median')),\n"
    "        ('scaler', StandardScaler())\n"
    "    ])\n"
    "    cat_ohe = Pipeline([\n"
    "        ('imputer', SimpleImputer(strategy='constant', fill_value='Missing')),\n"
    "        ('ohe', OneHotEncoder(handle_unknown='ignore', sparse_output=False))\n"
    "    ])\n"
    "    cat_ord = Pipeline([\n"
    "        ('imputer', SimpleImputer(strategy='constant', fill_value='Missing')),\n"
    "        ('ord', OrdinalEncoder(handle_unknown='use_encoded_value', unknown_value=-1))\n"
    "    ])\n"
    "    \n"
    "    preprocess_linear = ColumnTransformer([\n"
    "        ('num', numeric_pipe, numeric_cols),\n"
    "        ('cat', cat_ohe, cat_cols)\n"
    "    ], remainder='drop', verbose_feature_names_out=False)\n"
    "    \n"
    "    preprocess_tree = ColumnTransformer([\n"
    "        ('num', 'passthrough', numeric_cols),\n"
    "        ('cat', cat_ord, cat_cols)\n"
    "    ], remainder='drop', verbose_feature_names_out=False)\n"
    "    \n"
    "    preprocess_nn = ColumnTransformer([\n"
    "        ('num', numeric_pipe, numeric_cols),\n"
    "        ('cat', cat_ord, cat_cols)\n"
    "    ], remainder='drop', verbose_feature_names_out=False)\n"
    "    \n"
    "    # Fit & transform\n"
    "    X_train_linear = preprocess_linear.fit_transform(train_X)\n"
    "    X_test_linear = preprocess_linear.transform(test_X)\n"
    "    X_train_tree = preprocess_tree.fit_transform(train_X)\n"
    "    X_test_tree = preprocess_tree.transform(test_X)\n"
    "    X_train_nn = preprocess_nn.fit_transform(train_X)\n"
    "    X_test_nn = preprocess_nn.transform(test_X)\n"
    "    \n"
    "    # Target encoding\n"
    "    le = LabelEncoder()\n"
    "    y_train = le.fit_transform(train_y)\n"
    "    y_test = le.transform(test_y)\n"
    "    print(f\"Classes: {list(le.classes_)} -> {list(le.transform(le.classes_))}\")\n"
    "    \n"
    "    # Class weights\n"
    "    cw = compute_class_weight('balanced', classes=np.unique(y_train), y=y_train)\n"
    "    class_weight_dict = dict(zip(np.unique(y_train), cw))\n"
    "    print(f\"Class weights: {{k: round(v,4) for k,v in class_weight_dict.items()}}\")\n"
    "    \n"
    "    print(f\"Linear shapes: train {X_train_linear.shape}, test {X_test_linear.shape}\")\n"
    "    print(f\"Tree shapes:   train {X_train_tree.shape}, test {X_test_tree.shape}\")\n"
    "    print(f\"NN shapes:     train {X_train_nn.shape}, test {X_test_nn.shape}\")\n"
    "    \n"
    "    save_checkpoint(CHECKPOINT_NAME, {\n"
    "        'preprocess_linear': preprocess_linear,\n"
    "        'preprocess_tree': preprocess_tree,\n"
    "        'preprocess_nn': preprocess_nn,\n"
    "        'le': le,\n"
    "        'X_train_linear': X_train_linear,\n"
    "        'X_test_linear': X_test_linear,\n"
    "        'X_train_tree': X_train_tree,\n"
    "        'X_test_tree': X_test_tree,\n"
    "        'X_train_nn': X_train_nn,\n"
    "        'X_test_nn': X_test_nn,\n"
    "        'y_train': y_train,\n"
    "        'y_test': y_test,\n"
    "        'class_weight_dict': class_weight_dict\n"
    "    })"
))

